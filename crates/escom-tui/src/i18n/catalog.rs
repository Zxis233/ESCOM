use super::Language;
macro_rules! catalog {
    ($($key:ident => ($en:expr, $zh:expr)),* $(,)?) => {
        #[derive(Debug, Clone, Copy, PartialEq, Eq)]
        pub enum Key { $($key),* }
        impl Key {
            pub const fn text(self, language: Language) -> &'static str {
                match (self, language) { $((Self::$key, Language::En) => $en, (Self::$key, Language::ZhCn) => $zh),* }
            }
            #[cfg(test)] pub const ALL: &'static [Self] = &[$(Self::$key),*];
        }
    }
}
